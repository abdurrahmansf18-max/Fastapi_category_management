const SUPPORTED_LANGS = ['en', 'tr', 'ar'];
const DEFAULT_LANG = 'en';

function readCookieLanguage(): string | null {
  if (typeof document === 'undefined') return null;
  const hit = document.cookie
    .split(';')
    .map((chunk) => chunk.trim())
    .find((chunk) => chunk.startsWith('NEXT_LOCALE='));
  if (!hit) return null;
  const value = decodeURIComponent(hit.split('=')[1] || '').toLowerCase();
  return SUPPORTED_LANGS.includes(value) ? value : null;
}

function detectClientPreferredLanguage(): string {
  const cookieLang = readCookieLanguage();
  if (cookieLang) return cookieLang;

  const saved = localStorage.getItem('appLanguage');
  if (saved && SUPPORTED_LANGS.includes(saved)) return saved;

  const browserLang = (navigator.language || DEFAULT_LANG).split('-')[0].toLowerCase();
  return SUPPORTED_LANGS.includes(browserLang) ? browserLang : DEFAULT_LANG;
}

const initialLanguage =
  typeof window === 'undefined' ? DEFAULT_LANG : detectClientPreferredLanguage();

if (typeof window !== 'undefined') {
  document.documentElement.lang = initialLanguage;
  document.documentElement.dir = initialLanguage === 'ar' ? 'rtl' : 'ltr';
}

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: initialLanguage,
    fallbackLng: DEFAULT_LANG,
    interpolation: {
      escapeValue: false,
    }
  });

if (typeof window !== 'undefined') {
  const preferred = detectClientPreferredLanguage();
  if (preferred !== i18n.language) {
    i18n.changeLanguage(preferred);
  }
}

i18n.on('languageChanged', (lng) => {
  if (typeof window === 'undefined') return;
  localStorage.setItem('appLanguage', lng);
  document.cookie = `NEXT_LOCALE=${lng}; path=/; max-age=31536000; SameSite=Lax`;
  document.documentElement.lang = lng;
  document.documentElement.dir = lng === 'ar' ? 'rtl' : 'ltr';
});

export default i18n;
